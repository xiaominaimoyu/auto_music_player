package com.automusic.player.core

/**
 * 简谱识别输出协议(与桌面版 core/prompt.py 的 JIANPU_PROMPT 一致):
 * 引导外部 AI 工具把任意简谱图/文转成规范化文本,供解析器直接消费。
 */
object Prompt {
    const val JIANPU_PROMPT: String = """你是一位简谱识别专家。请把输入的乐谱内容转成以下严格格式的简谱文本:

规则:
1. 音高:中音用数字 1-7;高音在数字后加英文单引号 ' (如 5');低音在数字后加英文逗号 , (如 5,);休止符用 0
2. 半音:升半音必须保留,统一写在数字后面 # (如 1#、5'#);不要把 # 当作装饰记号丢弃
3. 时值:不加符号=四分音符;数字后跟一个下划线 _ = 八分音符,两个 __ = 十六分音符;跟一个减号 - = 二分音符,两个 -- = 全音符;附点用 · 加在时值符号后(如 5_· 是附点八分音符)
4. 和弦:多个同时演奏的音用方括号括起、空格分隔,时值符号加在右括号后(如 [1' 3' 5']- 是二分和弦);和弦内的音只写音高不写时值
5. 每个音符(或和弦)之间用空格分隔
6. 小节线、调号(如 1=C)、拍号、歌词、装饰音符号、力度记号全部丢弃,只输出音符序列
7. 只输出简谱本身,不要输出任何解释文字,不要用代码块包裹

示例输入(图片或文字):[简谱]
示例输出:1 1 5 5 6 6 5- 4 4 3 3 2 2 1-"""

    /** 内置样例(空库时端到端跑通流程用)。 */
    const val SAMPLE_JIANPU: String =
        "1 1 5, 5, 6 6 5'- 4 4 3 3 2 2 1- 0 0 [1' 3' 5']- 1 2 3_ 3_ 5_· 5_"
}
